/**
 * Emits `src/design-system/preview/_tokens.css` from the real `@theme` block.
 *
 * The previous preview bundle was hand-written, which is why it was still
 * showing a palette two directions old: nothing connected the published
 * swatches to the values the app actually compiles. This reads `index.css` and
 * derives the stylesheet, so a token change is one `npm run design:preview`
 * away from being visible on the cards.
 *
 * The HTML pages beside it are hand-written on purpose — they are argument and
 * example, not data.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const css = readFileSync(resolve(root, 'index.css'), 'utf8');

/** Pulls `--name: value;` pairs out of a named block. */
function tokensIn(opener) {
  const start = css.indexOf(opener);
  if (start === -1) throw new Error(`Block not found: ${opener}`);
  const body = css.slice(start, css.indexOf('\n}', start));
  return [...body.matchAll(/^\s*(--[a-z0-9-]+):\s*([^;]+);/gim)].map(([, name, value]) => [
    name,
    value.trim(),
  ]);
}

const theme = tokensIn('@theme {');
const dark = tokensIn('.dark {');

// The preview pages use short names (`--ink`, `--rule`) rather than the app's
// Tailwind-namespaced ones, because they are hand-written CSS rather than
// utilities. This is the only mapping, and it is mechanical.
const shorten = (name) => name.replace(/^--color-/, '--');

const declare = (pairs) =>
  pairs.map(([name, value]) => `  ${shorten(name)}: ${value};`).join('\n');

const out = `/* GENERATED by scripts/build-design-preview.mjs — do not edit.
   Source of truth: index.css. Run \`npm run design:preview\` to regenerate. */

@import url('https://fonts.googleapis.com/css2?family=Inter+Tight:wght@400;500;600;700&family=IBM+Plex+Mono:wght@400;500;600&family=Noto+Sans+Bengali:wght@400;500;600&display=swap');

:root {
${declare(theme)}
}

@media (prefers-color-scheme: dark) {
  :root {
${declare(dark).replace(/^ {2}/gm, '    ')}
  }
}

* { box-sizing: border-box; }

body {
  margin: 0;
  padding: 32px;
  background: var(--paper);
  color: var(--ink);
  font-family: var(--font-sans);
  font-size: var(--text-base);
  line-height: var(--text-base--line-height);
  /* Tabular figures everywhere, so columns of money line up without per-cell
     work. This is the single biggest reason the app reads as a ledger. */
  font-variant-numeric: tabular-nums;
}

h1 { font-size: var(--text-2xl); line-height: var(--text-2xl--line-height); letter-spacing: var(--tracking-tight); font-weight: var(--font-weight-semibold); margin: 0 0 8px; }
h2 { font-size: var(--text-lg); line-height: var(--text-lg--line-height); font-weight: var(--font-weight-semibold); margin: 32px 0 12px; }
h3 { font-size: var(--text-md); font-weight: var(--font-weight-semibold); margin: 20px 0 8px; }

.lede { color: var(--ink-2); max-width: var(--container-prose); margin: 0 0 24px; }

.note {
  color: var(--ink-3);
  font-size: var(--text-sm);
  line-height: var(--text-sm--line-height);
  max-width: var(--container-prose);
  margin: 10px 0 0;
}

.panel {
  background: var(--sheet);
  border: 1px solid var(--rule);
  border-radius: var(--radius-lg);
  padding: 16px;
}

.row { display: flex; flex-wrap: wrap; gap: 10px; align-items: center; }

.mono { font-family: var(--font-mono); font-size: var(--text-sm); }

.label {
  font-size: var(--text-2xs);
  text-transform: uppercase;
  letter-spacing: var(--tracking-caps);
  font-weight: var(--font-weight-semibold);
  color: var(--ink-3);
}
`;

const target = resolve(root, 'src/design-system/preview/_tokens.css');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out, 'utf8');

console.log(`✓ _tokens.css — ${theme.length} theme tokens, ${dark.length} dark overrides`);
